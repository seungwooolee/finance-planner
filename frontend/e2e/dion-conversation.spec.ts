import { expect, test } from '@playwright/test';
import { prepare } from './consultation-helpers';

test('consented dialogue persists, survives a lost response, and stays bound to the result', async ({ page, request }) => {
  test.setTimeout(150_000);
  const { first, base } = await prepare(page, request);
  const original = await (await request.get(`${base}/analyses/${first.run_id}`, { headers: { Authorization: 'Bearer MOCK-FE-ONLY' } })).json();
  await page.getByRole('button', { name: new RegExp(first.run_id) }).click();
  const launcher = page.getByRole('button', { name: 'dion AI 상담 열기', exact: true });
  await launcher.press('Enter');
  const panel = page.getByRole('region', { name: '결과 상담', exact: true });
  await panel.getByRole('button', { name: '임시 상담 시작', exact: true }).click();
  const enable = panel.getByRole('button', { name: '동의하고 AI 대화 시작', exact: true });
  await expect(enable).toBeDisabled();
  await panel.getByLabel('대화 원문 보관과 최근 대화·결과 근거의 외부 AI 전송에 동의해요.', { exact: true }).check();
  await enable.press('Enter');
  const input = panel.getByLabel('DION에게 메시지', { exact: true });
  await input.fill('왜 이런 결과인가요?');
  await panel.getByRole('button', { name: '메시지 보내기', exact: true }).click();
  const log = panel.getByRole('log', { name: 'DION 대화 내역' });
  await expect(log.getByRole('article')).toHaveCount(2);
  await expect(input).toHaveValue('');
  await expect(log).toContainText('왜 이런 결과인가요?');
  await log.getByText('이 답변의 결과 근거', { exact: true }).click();
  await expect(log).toContainText('저장된 계산 결과');
  await panel.getByRole('button', { name: '대화 원문 포함 상담 이어서 저장 (7일)', exact: true }).click();
  await expect(panel).toContainText('이어서 저장 중');
  let calls = 0;
  await page.route('**/agent-sessions/*/messages', async route => {
    calls++;
    const response = await route.fetch({ url: `${process.env.DION_TEST_BE_URL}${new URL(route.request().url()).pathname}` });
    if (calls === 1) return route.fulfill({ status: 503, json: { detail: { code: 'RESPONSE_LOST' } } });
    await route.fulfill({ response });
  });
  await input.fill('그 이유를 더 알려주세요');
  await panel.getByRole('button', { name: '메시지 보내기', exact: true }).click();
  await expect(panel.getByRole('alert')).toContainText('작성 내용과 기존 진단은 그대로');
  await expect(input).toHaveValue('그 이유를 더 알려주세요');
  await panel.getByRole('button', { name: '같은 요청 다시 시도', exact: true }).click();
  await expect(log.getByRole('article')).toHaveCount(4);
  expect(calls).toBe(2);
  await page.keyboard.press('Escape');
  await expect(launcher).toBeFocused();
  await launcher.click();
  await panel.getByRole('button', { name: '저장 상담 목록', exact: true }).click();
  await panel.getByRole('button', { name: /저장 상담 재개/ }).click();
  await expect(log.getByRole('article')).toHaveCount(4);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await log.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);
  const saved = await (await request.get(`${base}/analyses/${first.run_id}`, { headers: { Authorization: 'Bearer MOCK-FE-ONLY' } })).json();
  expect(saved.input_hash).toBe(original.input_hash);
  await panel.getByRole('button', { name: 'AI 대화 전송 중지', exact: true }).click();
  await expect(input).toHaveCount(0);
  await expect(log.getByRole('article')).toHaveCount(4);
});
