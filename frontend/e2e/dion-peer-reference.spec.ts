import { expect, test } from '@playwright/test';

test('reviewed research reaches real results with source, cohort, withholding and mobile display', async ({ page }, info) => {
  test.setTimeout(180000); // Includes the first Windows/Next development compilation.
  await page.goto('/dion');
  const response = page.waitForResponse(r => r.url().endsWith('/api/fe/v1/preview') && r.request().method() === 'POST');
  await page.getByRole('button', { name: '예시로 결과 보기 · 대표상품 포함', exact: true }).click();
  const result = (await (await response).json()).result;
  const review = result.peer_reference;
  expect(review.records).toHaveLength(34);
  expect(review.records.filter((r: { review_status: string }) => r.review_status === 'REFERENCE_ONLY')).toHaveLength(21);
  await page.locator('.d-tabs button').nth(0).click();
  const panel = page.getByRole('region', { name: '보유자산 · 참고 통계와 함께 보기', exact: true });
  await expect(panel).toHaveCount(1);
  await expect(page.getByRole('region', { name: '생활단계 참고 통계', exact: true })).toHaveCount(0);
  await expect(panel.getByRole('figure', { name: '현재 자산과 과거 조사 통계의 금액 그래프' })).toBeVisible();
  await panel.getByLabel('비교할 참고 집단').selectOption('C07');
  const total = panel.locator('[data-statistic-id="V001"]');
  await expect(total).toContainText('5억 6,678만원');
  await expect(panel).toContainText('2025-03-31');
  await expect(panel).toContainText('집단·포함 항목·기준일이 달라질 수 있는 과거 참고값');
  await panel.getByText('출처·정의·자료 기준 확인', { exact: true }).click();
  await expect(panel.getByRole('link', {name:/가계금융복지조사/}).first()).toHaveAttribute('href', /list_no=439535/);
  await panel.screenshot({ path: info.outputPath('peer-reference-desktop.png') });
  await panel.getByLabel('순자산 참고값').selectOption('중앙값');
  await expect(panel.locator('[data-statistic-id="V005"]')).toContainText('중앙값');
  await expect(panel.locator('[data-statistic-id="V005"]')).toContainText('2억 3,860만원');
  const withheld = review.records.find((r: { statistic_id: string }) => r.statistic_id === 'V015');
  expect(withheld.review_status).not.toBe('REFERENCE_ONLY');
  await expect(panel.getByLabel('비교할 참고 집단').locator('option[value="C14"]')).toHaveCount(0);
  await expect(panel.locator('[data-statistic-id="V015"]')).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await panel.getByLabel('비교할 참고 집단').selectOption('C08');
  await expect(panel).toContainText('가구주 39세 이하');
  await panel.screenshot({ path: info.outputPath('peer-reference-mobile.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBeTruthy();
  await page.locator('.d-tabs button').nth(2).click();
  const preference = page.getByRole('region', { name: '투자선호 조사와의 비교', exact: true });
  await expect(preference).toContainText('원 질문·분류 절차와 이용조건');
  await expect(preference).not.toContainText('14.4%');
});
