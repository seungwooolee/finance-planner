import { expect, test } from '@playwright/test';

test('reviewed research reaches real results with source, cohort, withholding and mobile display', async ({ page }, info) => {
  test.setTimeout(180000); // Includes the first Windows/Next development compilation.
  await page.goto('/dion');
  await page.getByRole('button', { name: '심사용 가상사례', exact: true }).click();
  const response = page.waitForResponse(r => r.url().endsWith('/api/fe/v1/preview') && r.request().method() === 'POST');
  await page.getByRole('button', { name: '사회초년생 불러오기', exact: true }).click();
  const result = (await (await response).json()).result;
  const review = result.peer_reference;
  expect(review.records).toHaveLength(62);
  expect(review.records.filter((r: { review_status: string }) => r.review_status === 'REFERENCE_ONLY')).toHaveLength(49);
  await page.locator('.d-tabs button').nth(0).click();
  const panel = page.getByRole('region', { name: '보유자산 · 참고 통계와 함께 보기', exact: true });
  await expect(panel).toHaveCount(1);
  await expect(panel).toContainText('내 현재값 · 개인');
  await expect(panel.locator('[data-asset-series="own"][data-value="12000000"]')).toHaveCount(1);
  await expect(panel.locator('[data-statistic-id="V043"] [data-asset-series="reference"]')).toHaveAttribute("data-value","50120000");
  await expect(panel.getByRole('combobox')).toHaveValue("ANSWER");
  const table = panel.getByRole('table', {name: '내 자산과 조사 평균', exact: true});
  await expect(table.getByRole('columnheader', {name: '내 현재값 · 개인'})).toBeVisible();
  await expect(table.locator('[data-asset-series="own"]')).toHaveText(['1,200만원', '500만원', '700만원']);
  await expect(panel.getByText('통계 출처와 기준일', {exact: true})).toBeVisible();
  await expect(panel.getByRole('radio')).toHaveCount(0);
  await expect(panel.getByText('금액축:', {exact: false})).toHaveCount(0);
  const summaryCards = page.getByRole('region', {name: '내 상황 한눈에'}).locator('.d-personal-flow > li');
  await expect(summaryCards).toHaveCount(2);
  expect(await summaryCards.evaluateAll(cards => cards[0].getBoundingClientRect().top === cards[1].getBoundingClientRect().top)).toBe(true);
  await expect(page.getByRole('region', { name: '생활단계 참고 통계', exact: true })).toHaveCount(0);
  await expect(panel.getByRole('figure', { name: '현재 자산과 과거 조사 통계의 금액 그래프' })).toBeVisible();
  const withheld = review.records.find((r: { statistic_id: string }) => r.statistic_id === 'V015');
  expect(withheld.review_status).not.toBe('REFERENCE_ONLY');
  expect(withheld.value).toBeNull();
  expect(withheld.source_value).toBeNull();
  await expect(panel.locator('[data-statistic-id="V015"]')).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await panel.screenshot({ path: info.outputPath('peer-reference-mobile.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBeTruthy();
  await page.locator('.d-tabs button').nth(2).click();
  const preference = page.getByRole('region', { name: '투자선호 조사와의 비교', exact: true });
  await expect(preference).toHaveCount(0);
  await expect(page.getByText('14.4%', {exact: true})).toHaveCount(0);
  const composition = page.locator('#dion-selected-composition');
  for (const [type, label] of [['STABLE', '안정형'], ['BALANCED', '중립형'], ['RETURN', '위험추구형']]) {
    const button = page.locator(`[data-portfolio-apply="${type}"]`);
    await expect(button).toHaveAccessibleName(type === "STABLE" ? `${label} 선택` : `${label} 목표 비중 비교`);
    await button.press('Enter');
    await expect(button).toHaveAttribute('aria-pressed', 'true');
    await expect(button).toBeFocused();
    await expect(composition.getByRole('heading', {name: `${label} 구성 상세`})).toBeVisible();
    await expect(composition).toContainText('검토 배분액');
  }
  await composition.getByRole('button', {name: '상품 정보 자세히 보기 →'}).click();
  const products = page.getByRole('region', {name: '자산군별 상품 비교 후보'});
  await expect(products.locator('[data-candidate-code]')).toHaveCount(29);
  await expect(products.getByText('공시 참고', {exact: true}).first()).toBeVisible();
  const month = result.results['OUT-06'].candidates[0].rows[0].portfolio_type_views.RETURN;
  await expect(page.locator('[data-allocation-month]').first()).toHaveAttribute('data-allocated', month.allocated_total_krw);
  await expect(page.getByRole('article', { name: '선택 보류 · 배분 검토 내역' })).toBeVisible();
  await expect(page.getByRole('article', { name: '추천 상품' }).getByRole('button', {name: /최종안에 추가/})).toHaveCount(0);
  await page.getByRole('button', {name:'투자구성 비교로 돌아가기'}).click();
  await expect(page.locator('[data-portfolio-apply="RETURN"]')).toHaveAttribute('aria-pressed','true');
  await page.locator('.d-tabs button').nth(4).click();
  const assumptions = page.locator('.d-results > :last-child');
  await expect(assumptions).toHaveAttribute('id', 'dion-proposal-assumptions');
  await expect(assumptions.getByText('물가상승률', {exact:true})).toBeHidden();
  await assumptions.locator('summary').press('Enter');
  await expect(assumptions.getByText('연 2%', {exact:true})).toBeVisible();
  await assumptions.locator('summary').press('Space');
  await expect(assumptions.getByText('물가상승률', {exact:true})).toBeHidden();
  const pension = page.locator('[data-tax-benefit="pension-contribution"]');
  await expect(pension).toContainText('다음 확인');
  await pension.getByRole('button', {name: '근거로 자세히 보기'}).click();
  const guide = page.getByRole('dialog', {name: '연금저축·IRP 추가 납입 · 근거 설명'});
  await expect(guide.getByRole('heading', {name: '2026년 등록 근거'})).toBeVisible();
  await expect(guide.getByRole('link')).toHaveAttribute('href', /^https:\/\/www\.law\.go\.kr\//);
  await expect(guide).toContainText('원천징수영수증');
  await page.keyboard.press('Escape');
  await expect(pension.getByRole('button', {name: '근거로 자세히 보기'})).toBeFocused();
});
