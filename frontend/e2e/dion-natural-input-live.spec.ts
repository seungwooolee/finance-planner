import { expect, test } from '@playwright/test';
import { prepare } from './consultation-helpers';

test('explicit live model candidate is reviewed and confirmed without rewriting diagnosis', async ({page, request}) => {
  test.skip(process.env.DION_TEST_LIVE_AI !== '1', 'Paid synthetic validation requires explicit opt-in and a provisioned server grant.');
  test.setTimeout(120_000);
  const {first, base} = await prepare(page, request, false, true);
  const headers = {Authorization: 'Bearer MOCK-FE-ONLY'};
  const before = await (await request.get(`${base}/analyses/${first.run_id}`, {headers})).json();
  await page.getByRole('button', {name: new RegExp(first.run_id)}).click();
  await page.getByRole('button', {name: 'dion AI 상담 열기', exact: true}).click();
  const session = page.getByRole('region', {name: '결과 상담', exact: true});
  await session.getByRole('combobox', {name: '상담할 결과', exact: true}).selectOption('OUT-05');
  await session.getByRole('button', {name: '임시 상담 시작', exact: true}).click();
  const assistant = session.getByRole('region', {name: '말로 적고 입력 후보 확인'});
  await assistant.getByLabel('확인할 내용', {exact: true}).fill('매달 세금을 떼고 통장에 들어오는 돈은 287.5만원이에요.');
  await assistant.getByLabel('이 문장을 AI에 보내 다양한 표현의 후보 찾기', {exact: true}).check();
  const pending = page.waitForResponse(r => r.url().endsWith('/input-previews') && r.request().method() === 'POST');
  await assistant.getByRole('button', {name: '입력 후보 찾기', exact: true}).click();
  const response = await pending;
  expect(response.status()).toBe(200);
  const preview = await response.json();
  expect(preview.source).toBe('ONEPORT');
  expect(preview.fallback_code).toBeNull();
  expect(preview.candidates).toHaveLength(1);
  expect(preview.candidates[0].normalized_value).toBe('2875000');
  await expect(assistant.getByRole('status')).toHaveText('AI 추출 후보 · 아직 확인 전');
  await assistant.getByRole('button', {name: '이 후보 검토 · 월평균 세후소득'}).click();
  const editor = assistant.getByRole('form', {name: '후보의 뜻과 값 검토'});
  await expect(editor.getByLabel('확인한 값', {exact: true})).toHaveValue('287.5');
  await editor.getByLabel('본인의 실제 답변이며 항목·값·단위·기간·포함 관계를 확인했어요').check();
  await editor.getByRole('button', {name: '이 후보를 상담 확인으로 보내기'}).click();
  await expect(session.getByRole('region', {name: '답변 충돌 확인'})).toBeVisible();
  await session.getByRole('button', {name: '이 내용으로 상담 사실 확인', exact: true}).click();
  await expect(session.getByRole('status').filter({hasText: '상담 기억만 갱신'})).toBeVisible();
  const state = await (await request.get(`${base}/agent-sessions/${preview.session_id}`, {headers})).json();
  expect(state.confirmation_receipts.at(-1).operation).toBe('CONSULTATION_ONLY');
  expect(state.application_status).toBe('NOT_APPLIED');
  expect(await (await request.get(`${base}/analyses/${first.run_id}`, {headers})).json()).toEqual(before);
  await assistant.scrollIntoViewIfNeeded();
  await page.screenshot({path: test.info().outputPath('live-ai-confirmed.png')});
});
